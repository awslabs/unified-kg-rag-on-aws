"""Generate docs/cli.md from the argparse parsers of the CLIs.

Every flag's name, default, choices and description come from the parsers the
``pyproject`` scripts build, so the reference cannot drift from the code:
``tests/unit/test_cli_reference.py`` fails when the committed file differs from
what this script writes.

Usage:
    uv run python scripts/gen_cli_reference.py          # rewrite the file
    uv run python scripts/gen_cli_reference.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import os
import sys
from collections.abc import Callable, Iterator
from contextlib import contextmanager
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "docs" / "cli.md"
# The argument group every model- or store-using CLI shares
# (``application.cli.provider_args``); it is listed once, not per command.
PROVIDER_GROUP = "providers"

# Environment variables some parsers read for a flag's default; cleared while
# the parsers are built so the reference does not depend on the shell.
ENV_DEFAULTS = ("UKR_SOURCE_DIRECTORY", "UKR_PIPELINE_ID")

# (command, user-guide section, factory). The factories are imported lazily so
# importing this module stays cheap.
COMMANDS: list[tuple[str, str, str]] = [
    ("run-ingestion", "3-ingestion-run-ingestion", "ingestion"),
    ("run-rag", "4-querying-run-rag", "rag"),
    ("run-eval", "6-evaluation-run-eval", "eval"),
    ("run-visualization", "7-visualization-run-visualization", "visualization"),
    ("run-prompt-tuning", "8-prompt-tuning-run-prompt-tuning", "prompt_tuning"),
    ("prepare-benchmark", "benchmarks-musique", "benchmark"),
]

HEADER = """\
# CLI Reference

<!-- Generated by scripts/gen_cli_reference.py from the CLI parsers; do not
edit by hand. Run the script after changing a flag or its help text. -->

> 🇰🇷 한국어 사용자 가이드: [docs/user-guide.ko.md](./user-guide.ko.md)
> (this reference is generated in English only)

Every flag of every command line tool, its default and what it does, taken
from the same parsers `--help` prints. What each tool is for and worked
examples are in the [User Guide](./user-guide.md); configuration keys are in
the [Configuration Reference](./configuration.md).

- **Defaults** are what a run gets when the flag is omitted: `off` for a
  switch, `—` for no value (the config, or the description, decides).
- **Configuration flags** (`--config-path`, `--allow-unknown-keys`) and the
  **provider flags** (`--backend`, `--llm-provider`, ...) are shared: each
  provider flag overrides one key of the loaded config, a key the file sets
  included ([Local mode](./user-guide.md#local-mode-no-aws)).
- **Exit codes** and the `--output-format json` result are described in
  [CLI exit codes and JSON output](./user-guide.md#cli-exit-codes-and-json-output).
"""


def _parsers() -> dict[str, Callable[[], argparse.ArgumentParser]]:
    from unified_kg_rag.application.cli import (
        prepare_benchmark,
        run_evaluation,
        run_ingestion_pipeline,
        run_prompt_tuning,
        run_rag_chain,
        run_visualization,
    )

    return {
        "ingestion": run_ingestion_pipeline.CommandLineInterface._setup_arguments,
        "rag": run_rag_chain.CommandLineInterface._setup_arguments,
        "eval": run_evaluation.CommandLineInterface._setup_arguments,
        "visualization": run_visualization._build_parser,
        "prompt_tuning": run_prompt_tuning._build_parser,
        "benchmark": prepare_benchmark._parser,
    }


@contextmanager
def _clean_environment() -> Iterator[None]:
    saved = {name: os.environ.pop(name) for name in ENV_DEFAULTS if name in os.environ}
    try:
        yield
    finally:
        os.environ.update(saved)


def build_parsers() -> dict[str, argparse.ArgumentParser]:
    """Each command's parser, built with the environment defaults cleared."""
    factories = _parsers()
    parsers = {}
    with _clean_environment():
        for command, _, key in COMMANDS:
            parser = factories[key]()
            parser.prog = command
            parsers[command] = parser
    return parsers


def documented_actions(parser: argparse.ArgumentParser) -> list[argparse.Action]:
    """The parser's actions the reference lists (all but ``--help``)."""
    return [
        action
        for action in parser._actions
        if not isinstance(action, argparse._HelpAction)
        and action.help is not argparse.SUPPRESS
    ]


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _flag(action: argparse.Action) -> str:
    if not action.option_strings:
        return f"`{action.metavar or action.dest}`"
    names = ", ".join(f"`{name}`" for name in action.option_strings)
    if action.nargs != 0 and action.metavar:
        names += f" `{action.metavar}`"
    return names


def _default(action: argparse.Action) -> str:
    if isinstance(action, argparse._StoreTrueAction):
        return "off"
    if isinstance(action, argparse._StoreFalseAction):
        return "on"
    if not action.option_strings:
        return "required"
    if action.required:
        return "required"
    default = action.default
    if default is None or default == [] or default is argparse.SUPPRESS:
        return "—"
    if isinstance(default, list | tuple):
        return ", ".join(f"`{item}`" for item in default)
    return f"`{default}`"


def _description(parser: argparse.ArgumentParser, action: argparse.Action) -> str:
    formatter = parser._get_formatter()
    text = formatter._expand_help(action) if action.help else ""
    text = _cell(text)
    if text and not text.endswith("."):
        text += "."
    choices = [str(choice) for choice in action.choices or []]
    if choices and not all(choice in text for choice in choices):
        text += " One of " + ", ".join(f"`{choice}`" for choice in choices) + "."
    return text.strip()


def _table(
    parser: argparse.ArgumentParser, actions: list[argparse.Action]
) -> list[str]:
    lines = ["| Flag | Default | Description |", "|---|---|---|"]
    for action in actions:
        lines.append(
            f"| {_flag(action)} | {_default(action)} | "
            f"{_description(parser, action)} |"
        )
    return lines


def _group_actions(
    parser: argparse.ArgumentParser, group: argparse._ArgumentGroup
) -> list[argparse.Action]:
    documented = documented_actions(parser)
    return [action for action in group._group_actions if action in documented]


def provider_group(parser: argparse.ArgumentParser) -> argparse._ArgumentGroup | None:
    """The shared provider-flag group of ``parser``, if it has one."""
    for group in parser._action_groups:
        if group.title == PROVIDER_GROUP:
            return group
    return None


def _section(command: str, guide: str, parser: argparse.ArgumentParser) -> str:
    lines = [f"## `{command}`", ""]
    if parser.description:
        lines += [_cell(parser.description), ""]
    guide_link = f"[User Guide](./user-guide.md#{guide})"
    if provider_group(parser) is not None:
        lines += [
            f"Guide: {guide_link}. Also takes the "
            "[provider flags](#provider-flags).",
            "",
        ]
    else:
        lines += [f"Guide: {guide_link}.", ""]
    actions = [
        action
        for group in parser._action_groups
        if group.title != PROVIDER_GROUP
        for action in _group_actions(parser, group)
    ]
    lines += _table(parser, actions)
    lines.append("")
    return "\n".join(lines)


def _provider_section(parsers: dict[str, argparse.ArgumentParser]) -> str:
    users = [name for name, parser in parsers.items() if provider_group(parser)]
    parser = parsers[users[0]]
    group = provider_group(parser)
    assert group is not None
    lines = [
        "## Provider flags",
        "",
        "Taken by "
        + ", ".join(f"`{name}`" for name in users)
        + ". "
        + _cell(group.description or ""),
        "",
    ]
    lines += _table(parser, _group_actions(parser, group))
    lines.append("")
    return "\n".join(lines)


def render() -> str:
    """The full text of docs/cli.md."""
    parsers = build_parsers()
    contents = [f"- [`{command}`](#{command})" for command, _, _ in COMMANDS]
    contents.append("- [Provider flags](#provider-flags)")
    sections = [
        _section(command, guide, parsers[command]) for command, guide, _ in COMMANDS
    ]
    sections.append(_provider_section(parsers))
    return HEADER + "\n" + "\n".join(contents) + "\n\n" + "\n".join(sections)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 when the committed file is out of date instead of writing it",
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text(encoding="utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is out of date: run "
                "`uv run python scripts/gen_cli_reference.py`",
                file=sys.stderr,
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
