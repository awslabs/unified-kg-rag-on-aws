"""Generate docs/configuration.md from the configuration models.

Every key's type, default and description come from the Pydantic models in
``unified_kg_rag/domain/models``, so the reference cannot drift from the code:
``tests/unit/test_config_reference.py`` fails when the committed file differs
from what this script writes.

Usage:
    uv run python scripts/gen_config_reference.py          # rewrite the file
    uv run python scripts/gen_config_reference.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import enum
import inspect
import json
import sys
import types
import typing
from pathlib import Path
from typing import Any

from pydantic import BaseModel
from pydantic.fields import FieldInfo

from unified_kg_rag.application.config import AWS_ENV_FALLBACKS, ENV_PREFIX
from unified_kg_rag.domain.models.config import MOVED_KEYS, Config

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "docs" / "configuration.md"
MAX_DEFAULT_CHARS = 60

HEADER = f"""\
# Configuration Reference

<!-- Generated by scripts/gen_config_reference.py from the configuration
models; do not edit by hand. Run the script after changing a config field. -->

> 🇰🇷 한국어 사용자 가이드: [docs/user-guide.ko.md §2](./user-guide.ko.md#2-설정)
> (this reference is generated in English only)

Every configuration key, its type, its built-in default and what it does,
one table per section. How the configuration is loaded (file, `backend`
preset, environment, CLI flags) and the settings most runs change are in the
[User Guide §2](./user-guide.md#2-configuration);
[`config-template.yaml`](../config-template.yaml) is a commented starting file.

- **Defaults** are the built-in values a key takes when the file, the
  environment and the flags leave it unset. `null` usually means "derived":
  the description says from what.
- **Environment.** Any key can be set as `{ENV_PREFIX}` followed by its path in
  upper case with `__` between the segments, for example
  `{ENV_PREFIX}AWS__NEPTUNE__ENDPOINT` for `aws.neptune.endpoint`; a list or
  mapping value takes JSON. {{aws_fallbacks}}
- **Unknown keys** fail the load (`--allow-unknown-keys` turns that into a
  warning). Keys that moved are refused with their new place; see
  [Moved keys](#moved-keys).
"""


def _model_in(annotation: Any) -> type[BaseModel] | None:
    """The model class an annotation holds (bare or ``| None``), else None."""
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        return annotation
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        if len(args) == 1:
            return _model_in(args[0])
    return None


def _type_name(annotation: Any) -> str:
    """A short, readable name for a field annotation."""
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        return _type_name(args[0])
    if origin is typing.Literal:
        return " \\| ".join(f"`{json.dumps(a)}`" for a in args)
    if origin in (typing.Union, types.UnionType):
        parts = [_type_name(a) for a in args if a is not type(None)]
        name = " \\| ".join(dict.fromkeys(parts))
        return f"{name} \\| null" if type(None) in args else name
    if origin in (list, tuple, set, frozenset):
        inner = ", ".join(_type_name(a) for a in args if a is not Ellipsis)
        return f"list[{inner}]" if inner else "list"
    if origin is dict:
        return f"dict[{', '.join(_type_name(a) for a in args)}]" if args else "dict"
    if inspect.isclass(annotation) and issubclass(annotation, enum.Enum):
        return " \\| ".join(f"`{json.dumps(m.value)}`" for m in annotation)
    if annotation is Path:
        return "path"
    if inspect.isclass(annotation):
        return {
            "str": "string",
            "int": "integer",
            "float": "number",
            "bool": "boolean",
            "SecretStr": "secret string",
        }.get(annotation.__name__, annotation.__name__)
    return str(annotation).replace("typing.", "")


def _constraints(field: FieldInfo) -> str:
    """The numeric and length bounds of a field, e.g. ``≥ 0, ≤ 1``."""
    names = {"ge": "≥", "gt": ">", "le": "≤", "lt": "<", "min_length": "min length"}
    bounds = []
    for item in field.metadata:
        for attr, symbol in names.items():
            value = getattr(item, attr, None)
            if value is not None:
                bounds.append(f"{symbol} {value}")
    return ", ".join(bounds)


def _default(value: Any) -> str:
    """A default value as compact JSON in a code span."""
    if isinstance(value, BaseModel):
        value = value.model_dump(mode="json")
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, Path):
        value = str(value)
    text = json.dumps(value, ensure_ascii=False, default=str)
    if len(text) > MAX_DEFAULT_CHARS:
        return "see `config-template.yaml`"
    return "`" + text.replace("|", "\\|") + "`"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _intro(cls: type[BaseModel], field: FieldInfo | None) -> str:
    """A section's introduction: its field description, else its docstring."""
    if field is not None and field.description:
        return _cell(field.description)
    doc = inspect.getdoc(cls) or ""
    return _cell(doc.split("\n\n")[0]) if doc else ""


def _section(
    path: str, cls: type[BaseModel], value: BaseModel, field: FieldInfo | None
) -> list[str]:
    """The tables of one section and, recursively, of its sub-sections."""
    rows, children = [], []
    for name, info in cls.model_fields.items():
        sub = _model_in(info.annotation)
        current = getattr(value, name)
        key = f"{path}.{name}" if path else name
        if sub is not None and (current is not None or info.default is None):
            if current is None:
                current = sub()
            children.append((key, sub, current, info))
            continue
        bounds = _constraints(info)
        type_cell = _type_name(info.annotation) + (f" ({bounds})" if bounds else "")
        rows.append(
            f"| `{name}` | {type_cell} | {_default(current)} | "
            f"{_cell(info.description or '')} |"
        )
    lines = [f"{'#' * min(2 + path.count('.'), 4)} `{path}`", ""]
    intro = _intro(cls, field)
    if intro:
        lines += [intro, ""]
    if rows:
        lines += [
            "| Key | Type | Default | Description |",
            "|---|---|---|---|",
            *rows,
            "",
        ]
    for key, sub, current, info in children:
        lines += _section(key, sub, current, info)
    return lines


def render() -> str:
    """The whole reference as Markdown."""
    config = Config()
    fallbacks = ", ".join(
        f"`{name}` fills `{'.'.join(path)}`" for name, path in AWS_ENV_FALLBACKS.items()
    )
    header = HEADER.replace(
        "{aws_fallbacks}",
        (
            f"The standard AWS variables also apply when nothing else sets the key: "
            f"{fallbacks}."
            if fallbacks
            else ""
        ),
    )
    lines = [header, "## Contents", ""]
    sections, top_rows = [], []
    for name, info in Config.model_fields.items():
        sub = _model_in(info.annotation)
        if sub is None:
            bounds = _constraints(info)
            type_cell = _type_name(info.annotation) + (f" ({bounds})" if bounds else "")
            top_rows.append(
                f"| `{name}` | {type_cell} | {_default(getattr(config, name))} | "
                f"{_cell(info.description or '')} |"
            )
            continue
        sections.append((name, sub, getattr(config, name), info))
    if top_rows:
        lines.append("- [Top-level keys](#top-level-keys)")
    lines += [f"- [`{name}`](#{name})" for name, *_ in sections]
    lines += ["- [Moved keys](#moved-keys)", ""]
    if top_rows:
        lines += [
            "## Top-level keys",
            "",
            "| Key | Type | Default | Description |",
            "|---|---|---|---|",
            *top_rows,
            "",
        ]
    for name, sub, value, info in sections:
        lines += _section(name, sub, value, info)
    lines += [
        "## Moved keys",
        "",
        "These keys are refused at load with the key that replaced them.",
        "",
        "| Former key | Now |",
        "|---|---|",
        *[f"| `{old}` | `{new}` |" for old, new in MOVED_KEYS.items()],
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the file is out of date"
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is out of date; run {Path(__file__).name}"
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
