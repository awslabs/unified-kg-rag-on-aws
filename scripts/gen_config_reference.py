"""Generate docs/reference/configuration.md from the configuration models.

Every key's type, default and description come from the Pydantic models in
``unified_kg_rag/domain/models``, so the reference cannot drift from the code:
``tests/unit/test_config_reference.py`` fails when the committed file differs
from what this script writes.

Usage:
    uv run python scripts/gen_config_reference.py          # rewrite the file
    uv run python scripts/gen_config_reference.py --check  # exit 1 if stale
"""

from __future__ import annotations

import argparse
import enum
import inspect
import json
import sys
import types
import typing
from pathlib import Path
from typing import Any

import yaml
from pydantic import BaseModel
from pydantic.fields import FieldInfo

from unified_kg_rag.application.config import AWS_ENV_FALLBACKS, ENV_PREFIX
from unified_kg_rag.domain.models.config import (
    DEPRECATED_KEYS,
    MOVED_KEY_NOTES,
    MOVED_KEYS,
    REMOVED_KEYS,
    Config,
)
from unified_kg_rag.domain.models.evidence import EVIDENCE_KINDS, EVIDENCE_MEANINGS

REPO_ROOT = Path(__file__).resolve().parent.parent
OUTPUT = REPO_ROOT / "docs" / "reference" / "configuration.md"
MAX_DEFAULT_CHARS = 60
# The evidence page, as linked from the reference.
EVIDENCE_LINK = "../concepts/defaults-and-evidence.md"
# The evidence tags of the defaults no run compared, in the order listed.
UNCOMPARED = ("deviation", "unmeasured")

HEADER = f"""\
# Configuration Reference

<!-- Generated by scripts/gen_config_reference.py from the configuration
models; do not edit by hand. Run the script after changing a config field. -->

> 🇰🇷 한국어 설정 가이드: [docs/guides/configure.ko.md](../guides/configure.ko.md)
> (this reference is generated in English only)

Every configuration key, its type, its built-in default and what it does,
one table per section. How the configuration is loaded (file, `backend`
preset, environment, CLI flags) and the settings most runs change are in the
[Configuration guide](../guides/configure.md);
[`config-template.yaml`](../../config-template.yaml) is a short starting file with
the keys most deployments set.

- **Defaults** are the built-in values a key takes when the file, the
  environment and the flags leave it unset. `null` usually means "derived":
  the description says from what.
- **Environment.** Any key can be set as `{ENV_PREFIX}` followed by its path in
  upper case with `__` between the segments, for example
  `{ENV_PREFIX}AWS__NEPTUNE__ENDPOINT` for `aws.neptune.endpoint`; a list or
  mapping value takes JSON. {{aws_fallbacks}}
- **Evidence.** Every numeric default says what it rests on:
{{evidence_kinds}}
  The defaults a run never compared are listed in
  [Defaults no run compared](#defaults-no-run-compared).
- **Unknown keys** fail the load (`--allow-unknown-keys` turns that into a
  warning). Keys that moved are refused with their new place; see
  [Moved keys](#moved-keys). Removed keys load with a warning and are
  ignored; see [Removed keys](#removed-keys).
"""


def _model_in(annotation: Any) -> type[BaseModel] | None:
    """The model class an annotation holds (bare or ``| None``), else None."""
    if inspect.isclass(annotation) and issubclass(annotation, BaseModel):
        return annotation
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        args = [a for a in typing.get_args(annotation) if a is not type(None)]
        if len(args) == 1:
            return _model_in(args[0])
    return None


def _item_model(annotation: Any) -> type[BaseModel] | None:
    """The model class of a list's items (``list[Model]``), else None."""
    if typing.get_origin(annotation) is list:
        (item,) = typing.get_args(annotation) or (None,)
        if inspect.isclass(item) and issubclass(item, BaseModel):
            return item
    return None


def _type_name(annotation: Any) -> str:
    """A short, readable name for a field annotation."""
    origin = typing.get_origin(annotation)
    args = typing.get_args(annotation)
    if origin is typing.Annotated:
        return _type_name(args[0])
    if origin is typing.Literal:
        return " \\| ".join(f"`{json.dumps(a)}`" for a in args)
    if origin in (typing.Union, types.UnionType):
        parts = [_type_name(a) for a in args if a is not type(None)]
        name = " \\| ".join(dict.fromkeys(parts))
        return f"{name} \\| null" if type(None) in args else name
    if origin in (list, tuple, set, frozenset):
        inner = ", ".join(_type_name(a) for a in args if a is not Ellipsis)
        return f"list[{inner}]" if inner else "list"
    if origin is dict:
        return f"dict[{', '.join(_type_name(a) for a in args)}]" if args else "dict"
    if inspect.isclass(annotation) and issubclass(annotation, enum.Enum):
        return " \\| ".join(f"`{json.dumps(m.value)}`" for m in annotation)
    if annotation is Path:
        return "path"
    if inspect.isclass(annotation):
        return {
            "str": "string",
            "int": "integer",
            "float": "number",
            "bool": "boolean",
            "SecretStr": "secret string",  # pragma: allowlist secret
        }.get(annotation.__name__, annotation.__name__)
    return str(annotation).replace("typing.", "")


def _constraints(field: FieldInfo) -> str:
    """The numeric and length bounds of a field, e.g. ``≥ 0, ≤ 1``."""
    names = {"ge": "≥", "gt": ">", "le": "≤", "lt": "<", "min_length": "min length"}
    bounds = []
    for item in field.metadata:
        for attr, symbol in names.items():
            value = getattr(item, attr, None)
            if value is not None:
                bounds.append(f"{symbol} {value}")
    return ", ".join(bounds)


def _default(value: Any, key: str, long_defaults: dict[str, Any]) -> str:
    """A default value as compact JSON in a code span; one too long for a
    table cell goes to ``long_defaults`` (the Long defaults section)."""
    if isinstance(value, BaseModel):
        value = value.model_dump(mode="json")
    if isinstance(value, enum.Enum):
        value = value.value
    if isinstance(value, Path):
        value = str(value)
    text = json.dumps(value, ensure_ascii=False, default=str)
    if len(text) > MAX_DEFAULT_CHARS:
        long_defaults[key] = json.loads(text)
        return "see [Long defaults](#long-defaults)"
    return "`" + text.replace("|", "\\|") + "`"


def _cell(text: str) -> str:
    return " ".join(text.split()).replace("|", "\\|")


def _evidence(field: FieldInfo) -> tuple[str | None, str | None]:
    """A field's evidence tag and its ref (``domain.models.evidence``)."""
    extra = field.json_schema_extra
    if not isinstance(extra, dict):
        return None, None
    kind, ref = extra.get("evidence"), extra.get("ref")
    return (
        kind if isinstance(kind, str) else None,
        ref if isinstance(ref, str) else None,
    )


def _evidence_cell(field: FieldInfo) -> str:
    """The Evidence cell: the tag, linked to its section of the evidence page
    or followed by its ref."""
    kind, ref = _evidence(field)
    if kind is None:
        return ""
    if ref and ref.startswith("#"):
        return f"[{kind}]({EVIDENCE_LINK}{ref})"
    return f"{kind}: {_cell(ref)}" if ref else kind


def _row(name: str, type_cell: str, default: str, field: FieldInfo) -> str:
    return (
        f"| `{name}` | {type_cell} | {default} | {_evidence_cell(field)} | "
        f"{_cell(field.description or '')} |"
    )


TABLE_HEAD = [
    "| Key | Type | Default | Evidence | Description |",
    "|---|---|---|---|---|",
]


def _intro(cls: type[BaseModel], field: FieldInfo | None) -> str:
    """A section's introduction: its field description, else its docstring."""
    if field is not None and field.description:
        return _cell(field.description)
    doc = inspect.getdoc(cls) or ""
    return _cell(doc.split("\n\n")[0]) if doc else ""


def _section(
    path: str,
    cls: type[BaseModel],
    value: BaseModel | None,
    field: FieldInfo | None,
    long_defaults: dict[str, Any],
    uncompared: list[tuple[str, str, FieldInfo]],
) -> list[str]:
    """The tables of one section and, recursively, of its sub-sections.

    ``value`` None: the section of a list's items (``path`` ends in
    ``[]``), whose defaults are the fields' own and whose required fields
    say so. A default no run compared goes to ``uncompared``."""
    rows: list[str] = []
    children: list[tuple[str, type[BaseModel], BaseModel | None, FieldInfo | None]]
    children = []
    for name, info in cls.model_fields.items():
        sub = _model_in(info.annotation)
        key = f"{path}.{name}" if path else name
        if value is None:
            current = (
                None
                if info.is_required()
                else info.get_default(call_default_factory=True)
            )
        else:
            current = getattr(value, name)
        if sub is not None and (current is not None or info.default is None):
            if current is None:
                current = sub()
            children.append((key, sub, current, info))
            continue
        bounds = _constraints(info)
        type_cell = _type_name(info.annotation) + (f" ({bounds})" if bounds else "")
        default = (
            "required"
            if value is None and info.is_required()
            else _default(current, key, long_defaults)
        )
        rows.append(_row(name, type_cell, default, info))
        if _evidence(info)[0] in UNCOMPARED:
            uncompared.append((key, default, info))
        if (item := _item_model(info.annotation)) is not None:
            children.append((f"{key}[]", item, None, None))
    lines = [f"{'#' * min(2 + path.count('.'), 4)} `{path}`", ""]
    intro = _intro(cls, field)
    if intro:
        lines += [intro, ""]
    if rows:
        lines += [*TABLE_HEAD, *rows, ""]
    for key, sub, current, info in children:
        lines += _section(key, sub, current, info, long_defaults, uncompared)
    return lines


def render() -> str:
    """The whole reference as Markdown."""
    config = Config()
    fallbacks = ", ".join(
        f"`{name}` fills `{'.'.join(path)}`" for name, path in AWS_ENV_FALLBACKS.items()
    )
    kinds = "\n".join(
        f"  - *{kind}*: {EVIDENCE_MEANINGS[kind]};" for kind in EVIDENCE_KINDS
    )
    header = HEADER.replace("{evidence_kinds}", kinds.rstrip(";") + ".").replace(
        "{aws_fallbacks}",
        (
            f"The standard AWS variables also apply when nothing else sets the key: "
            f"{fallbacks}."
            if fallbacks
            else ""
        ),
    )
    lines = [header, "## Contents", ""]
    sections, top_rows = [], []
    long_defaults: dict[str, Any] = {}
    uncompared: list[tuple[str, str, FieldInfo]] = []
    for name, info in Config.model_fields.items():
        sub = _model_in(info.annotation)
        if sub is None:
            bounds = _constraints(info)
            type_cell = _type_name(info.annotation) + (f" ({bounds})" if bounds else "")
            default = _default(getattr(config, name), name, long_defaults)
            top_rows.append(_row(name, type_cell, default, info))
            if _evidence(info)[0] in UNCOMPARED:
                uncompared.append((name, default, info))
            continue
        sections.append((name, sub, getattr(config, name), info))
    if top_rows:
        lines.append("- [Top-level keys](#top-level-keys)")
    lines += [f"- [`{name}`](#{name})" for name, *_ in sections]
    lines += [
        "- [Long defaults](#long-defaults)",
        "- [Defaults no run compared](#defaults-no-run-compared)",
        "- [Moved keys](#moved-keys)",
        "- [Removed keys](#removed-keys)",
        "",
    ]
    if top_rows:
        lines += ["## Top-level keys", "", *TABLE_HEAD, *top_rows, ""]
    for name, sub, value, info in sections:
        lines += _section(name, sub, value, info, long_defaults, uncompared)
    lines += ["## Long defaults", "", "The defaults too long for their table.", ""]
    for key, value in long_defaults.items():
        dumped = yaml.safe_dump(
            {key.rsplit(".", 1)[-1]: value}, allow_unicode=True, sort_keys=False
        )
        lines += [f"### `{key}`", "", "```yaml", dumped.rstrip(), "```", ""]
    order = {kind: rank for rank, kind in enumerate(UNCOMPARED)}
    uncompared.sort(key=lambda row: order[_evidence(row[2])[0] or ""])
    lines += [
        "## Defaults no run compared",
        "",
        "The numeric defaults that change what is retrieved or answered and "
        "that no run compared with another value: the departures from the "
        "original algorithm first, then the rest. They keep the values they "
        f"were written with. [Defaults and evidence]({EVIDENCE_LINK}) holds "
        "the defaults a run measured and how to compare settings on your own "
        "corpus.",
        "",
        "| Key | Default | Evidence |",
        "|---|---|---|",
        *[
            f"| `{key}` | {default} | {_evidence_cell(info)} |"
            for key, default, info in uncompared
        ],
        "",
        "## Moved keys",
        "",
        "These keys are refused at load with the key that replaced them.",
        "",
        "| Former key | Now |",
        "|---|---|",
        *[f"| `{old}` | `{new}` |" for old, new in MOVED_KEYS.items()],
        "",
        "Each takes the value of the key it replaces, except:",
        "",
        *[f"- `{old}`: {_cell(note)}." for old, note in MOVED_KEY_NOTES.items()],
        "",
        "## Deprecated keys",
        "",
        "These keys still load, into the key that replaces them, with a WARNING.",
        "",
        "| Deprecated key | Loads into |",
        "|---|---|",
        *[f"| `{old}` | `{new}` |" for old, new in DEPRECATED_KEYS.items()],
        "",
        "## Removed keys",
        "",
        "These keys, and any key under them, load with a WARNING and are " "ignored.",
        "",
        "| Former key | Why |",
        "|---|---|",
        *[f"| `{old}` | {_cell(why)} |" for old, why in REMOVED_KEYS.items()],
        "",
    ]
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument(
        "--check", action="store_true", help="exit 1 if the file is out of date"
    )
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != text:
            print(
                f"{OUTPUT.relative_to(REPO_ROOT)} is out of date; run {Path(__file__).name}"
            )
            return 1
        return 0
    OUTPUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
