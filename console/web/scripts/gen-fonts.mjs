/**
 * Write src/styles/fonts.css: the @font-face rules of the faces the console
 * bundles (SIL OFL 1.1, from the @fontsource packages), WOFF2 only and
 * only the subsets and weights the styles use (DESIGN.md). Each rule keeps
 * its unicode-range, so a browser fetches a subset only when the page shows
 * one of its characters. Also copies each family's licence to
 * public/licenses/.
 *
 *   node scripts/gen-fonts.mjs
 */
import { copyFile, mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

const FACES = [
  { pkg: "jetbrains-mono", weights: [400, 600], subsets: ["latin", "latin-ext", "cyrillic"] },
];

// Faces the styles import as their vendor ships them (unmodified files, so
// a Reserved Font Name stays valid): only their licences are copied here.
const VENDOR_LICENSES = [
  { pkg: "pretendard", file: "dist/LICENSE.txt" },
  { pkg: "pretendard-jp", file: "dist/LICENSE.txt" },
];

const root = new URL("..", import.meta.url).pathname;
const modules = join(root, "node_modules", "@fontsource");
const out = [
  "/* Generated by scripts/gen-fonts.mjs from the @fontsource packages; do not edit.",
  " * SIL Open Font License 1.1 (public/licenses/). */",
];
await mkdir(join(root, "public", "licenses"), { recursive: true });
for (const face of FACES) {
  for (const weight of face.weights) {
    const css = await readFile(join(modules, face.pkg, `${weight}.css`), "utf8");
    for (const match of css.matchAll(/\/\* (\S+) \*\/\s*@font-face \{([^}]*)\}/g)) {
      const [, name, body] = match;
      const subset = name.slice(face.pkg.length + 1, -`-${weight}-normal`.length);
      if (face.subsets && !face.subsets.includes(subset)) continue;
      const woff2 = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      if (!woff2) throw new Error(`${name}: no woff2`);
      const keep = body
        .split(";")
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith("src:"));
      const src = `src: url("../../node_modules/@fontsource/${face.pkg}/files/${woff2}") format("woff2")`;
      out.push(`@font-face {\n  ${[...keep, src].join(";\n  ")};\n}`);
    }
  }
  await copyFile(join(modules, face.pkg, "LICENSE"), join(root, "public", "licenses", `${face.pkg}.txt`));
}
for (const { pkg, file } of VENDOR_LICENSES) {
  // The text as shipped, less its lines' trailing blanks (the repository's
  // whitespace check).
  const text = await readFile(join(root, "node_modules", pkg, file), "utf8");
  const clean = text.replace(/[ \t]+$/gm, "").replace(/\s*$/, "\n");
  await writeFile(join(root, "public", "licenses", `${pkg}.txt`), clean);
}
await writeFile(join(root, "src", "styles", "fonts.css"), `${out.join("\n")}\n`);
console.log(`fonts.css: ${out.length - 2} faces`);
