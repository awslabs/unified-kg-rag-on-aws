/**
 * Write src/styles/fonts.css: the @font-face rules of the faces the console
 * bundles (SIL OFL 1.1, from the @fontsource packages), WOFF2 only and
 * only the subsets and weights the styles use (DESIGN.md): Atkinson
 * Hyperlegible Next and Mono (variable), JetBrains Mono's Cyrillic. Each
 * rule keeps its unicode-range, so a browser fetches a subset only when the
 * page shows one of its characters. Also copies each family's licence to
 * public/licenses/.
 *
 *   node scripts/gen-fonts.mjs
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";

// scope: the npm scope (@fontsource for static weights, @fontsource-variable
// for one variable file per subset); sheets: the package's stylesheets read;
// subsets: the ones kept.
const FACES = [
  {
    scope: "@fontsource-variable",
    pkg: "atkinson-hyperlegible-next",
    sheets: ["wght.css"],
    subsets: ["latin", "latin-ext"],
  },
  {
    scope: "@fontsource-variable",
    pkg: "atkinson-hyperlegible-mono",
    sheets: ["wght.css"],
    subsets: ["latin", "latin-ext"],
  },
  // Atkinson Hyperlegible Mono has no Cyrillic: the data face's Russian
  // (chart units, labels set in it) falls to JetBrains Mono's Cyrillic.
  { scope: "@fontsource", pkg: "jetbrains-mono", sheets: ["400.css", "600.css"], subsets: ["cyrillic"] },
];

// Faces the styles import as their vendor ships them (unmodified files, so
// a Reserved Font Name stays valid): only their licences are copied here.
const VENDOR_LICENSES = [
  { pkg: "pretendard", file: "dist/LICENSE.txt" },
  { pkg: "pretendard-jp", file: "dist/LICENSE.txt" },
];

const root = new URL("..", import.meta.url).pathname;
const modules = join(root, "node_modules");
const out = [
  "/* Generated by scripts/gen-fonts.mjs from the @fontsource packages; do not edit.",
  " * SIL Open Font License 1.1 (public/licenses/). */",
];

// The text as shipped, less its lines' trailing blanks (the repository's
// whitespace check).
async function copyLicense(from, name) {
  const text = await readFile(from, "utf8");
  const clean = text.replace(/[ \t]+$/gm, "").replace(/\s*$/, "\n");
  await writeFile(join(root, "public", "licenses", `${name}.txt`), clean);
}

await mkdir(join(root, "public", "licenses"), { recursive: true });
for (const face of FACES) {
  const dir = join(modules, face.scope, face.pkg);
  for (const sheet of face.sheets) {
    const css = await readFile(join(dir, sheet), "utf8");
    for (const match of css.matchAll(/\/\* (\S+) \*\/\s*@font-face \{([^}]*)\}/g)) {
      const [, name, body] = match;
      // <pkg>-<subset>-<400|wght>-<normal|italic>
      const parts = name.slice(face.pkg.length + 1).match(/^(.+)-(?:\d+|wght)-(normal|italic)$/);
      if (!parts) throw new Error(`${name}: unexpected face name`);
      const [, subset, style] = parts;
      if (style !== "normal" || !face.subsets.includes(subset)) continue;
      const woff2 = body.match(/url\(\.\/files\/([^)]+\.woff2)\)/)?.[1];
      if (!woff2) throw new Error(`${name}: no woff2`);
      const keep = body
        .split(";")
        .map((line) => line.trim())
        .filter((line) => line && !line.startsWith("src:"));
      const format = face.scope === "@fontsource-variable" ? "woff2-variations" : "woff2";
      const src = `src: url("../../node_modules/${face.scope}/${face.pkg}/files/${woff2}") format("${format}")`;
      out.push(`@font-face {\n  ${[...keep, src].join(";\n  ")};\n}`);
    }
  }
  await copyLicense(join(dir, "LICENSE"), face.pkg);
}
for (const { pkg, file } of VENDOR_LICENSES) {
  await copyLicense(join(modules, pkg, file), pkg);
}
await writeFile(join(root, "src", "styles", "fonts.css"), `${out.join("\n")}\n`);
console.log(`fonts.css: ${out.length - 2} faces`);
